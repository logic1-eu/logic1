class RingElement(Protocol):

    def __add__(self, other: Self) -> Self:
        ...

    def __sub__(self, other: Self) -> Self:
        ...

    def __mul__(self, other: Self) -> Self:
        ...

    def __neg__(self) -> Self:
        ...

    def __eq__(self, other: object) -> bool:
        ...

    def __pow__(self, n: int) -> Self:
        ...

    def __hash__(self) -> int:
        ...

    def is_constant(self) -> bool:
        ...


class Ring[π: RingElement, ρ](ABC):
    """Abstract base class for polynomial rings that wrap an underlying
    polynomial ring implementation. The type variable `π` represents the type of
    the polynomial elements, and `ρ` represents the type of the underlying
    wrapped ring.
    """

    _wrapped_ring: ρ
    """The underlying wrapped polynomial ring.
    """

    def __eq__(self, other: object) -> bool:
        # Depending on the implementation, it may be sufficient to check for
        # identical wrapped rings. For instance, FINT contexts are unique.
        if not isinstance(other, Ring):
            return False
        return self._wrapped_ring == other._wrapped_ring

    @abstractmethod
    def __init__(self, vars_: Iterable[str] = ()) -> None:
        """Initialize a polynomial ring with the given variable names.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> R = Ring(('x', 'y'))
        >>> R.get_names()
        ('x', 'y')
        """
        ...

    def __or__(self, other: Ring[π, ρ]) -> Self:
        """The ring generated by the union of the generators of ``self`` and
        ``other``.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> R1 = Ring(('x', 'y'))
        >>> R2 = Ring(('y', 'z'))
        >>> R1 | R2
        Ring(('x', 'y', 'z'))
        """
        if self._wrapped_ring is other._wrapped_ring:
            return self
        else:
            names = set(self.get_names()) | set(other.get_names())
            return self.__class__(names)

    def __repr__(self) -> str:
        """Return a string representation of the polynomial ring.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> Ring()
        Ring()
        >>> Ring(('y', 'x'))
        Ring(('x', 'y'))
        """
        names = tuple(str(g) for g in self.get_gens())
        if not names:
            return f"{self.__class__.__name__}()"
        else:
            return f"{self.__class__.__name__}({names})"

    @abstractmethod
    def coerce_poly(self, x: π) -> π:
        """Coerce a polynomial to the wrapped polynomial ring.
        """
        ...

    @classmethod
    def from_raw(cls, wrapped_ring: ρ) -> Self:
        """Create a polynomial ring from a wrapped ring object.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> from sage.all import PolynomialRing, QQ
        >>> sage_ring = PolynomialRing(QQ, 'x,y')
        >>> Ring.from_raw(sage_ring)
        Ring(('x', 'y'))
        """
        ring = cls.__new__(cls)
        ring._wrapped_ring = wrapped_ring
        return ring

    def get_names(self) -> tuple[str, ...]:
        """Return the names of the variables in the polynomial ring.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> R = Ring(('a', 'b', 'c'))
        >>> R.get_names()
        ('a', 'b', 'c')
        """
        return tuple(str(var) for var in self.get_gens())

    @abstractmethod
    def get_gens(self) -> tuple[π, ...]:
        """Return the generators of the wrapped polynomial ring.

        >>> from logic1.theories.RCF.sage.term import Ring
        >>> R = Ring(('x', 'y'))
        >>> R.get_gens()
        (x, y)
        """
        ...

    @staticmethod
    def sort_key(s: str) -> tuple[str, int]:
        """Sort key for variable names. The sort order is lexicographic, except
        that variables with the same name are ordered by their numeric suffix.

        >>> Ring.sort_key('x')
        ('x', -1)
        >>> Ring.sort_key('x1')
        ('x', 1)
        """
        base = s.rstrip('0123456789')
        index = s[len(base):]
        n = int(index) if index else -1
        return base, n


class VariableSet[χ: Variable](firstorder.VariableSet[χ]):

    _stack: list[set[str]]

    @property
    def stack(self) -> list[set[str]]:
        """Implements the abstract property :attr:`.firstorder.term.VariableSet.stack`.
        """
        return self._stack

    @property
    def _used(self) -> set[str]:
        return self._stack[-1]

    def __getitem__(self, name: str) -> χ:
        """Implements the abstract method :meth:`.firstorder.term.VariableSet.__getitem__`.

        >>> from logic1.theories.RCF import VV
        >>> isinstance(VV, VariableSet)
        True
        >>> x = VV['x']
        >>> isinstance(x, Variable)
        True
        """
        if not isinstance(name, str):
            raise TypeError(f'expecting string as index; {name} is {type(name)}')
        self._used.add(name)
        ring = self._ring_type()((name,))
        return self._variable_type()._from_gen(ring.get_gens()[0])

    def __init__(self) -> None:
        self._stack = [set()]

    def __repr__(self) -> str:
        return str(self)  # for now

    def __str__(self) -> str:
        names = sorted(self._used, key=self._ring_type().sort_key)
        s = ', '.join(name for name in (*names, '...'))
        return f'{{{s}}}'

    def fresh(self, suffix: str = '') -> χ:
        """Return a fresh variable, by default from the sequence G0001, G0002,
        ..., G9999, G10000, ... This naming convention is inspired by Lisp's
        gensym(). If the optional argument :data:`suffix` is specified, the
        sequence G0001<suffix>, G0002<suffix>, ... is used instead.

        >>> from logic1.theories.RCF import VV
        >>> VV.fresh('_demo')
        G0001_demo
        >>> VV.fresh('_demo')
        G0002_demo
        """
        i = 1
        v = f'G{i:04d}{suffix}'
        while v in self._used:
            i += 1
            v = f'G{i:04d}{suffix}'
        return self[v]

    def pop(self) -> None:
        if len(self._stack) <= 1:
            raise IndexError('pop at bottom of stack')
        from logic1.theories.RCF import cache_clear
        self._stack.pop()
        cache_clear()

    def push(self) -> None:
        from logic1.theories.RCF import cache_clear
        self._stack.append(set())
        cache_clear()

    def _reset(self) -> None:
        from logic1.theories.RCF import cache_clear
        self._stack = [set()]
        cache_clear()

    @staticmethod
    @abstractmethod
    def _ring_type() -> type[Ring]:
        ...

    @staticmethod
    @abstractmethod
    def _variable_type() -> type[χ]:
        ...


class Term[τ: Term,
           χ: Variable,
           κ, # sort key
           π: RingElement,
           ρ, # SAGE Polynomial Ring or FLINT Context
           T_Eq: AtomicFormula,
           T_Ge: AtomicFormula,
           T_Gt: AtomicFormula,
           T_Le: AtomicFormula,
           T_Lt: AtomicFormula,
           T_Ne: AtomicFormula,
      ](firstorder.Term[τ, χ, Number, κ]):

    _hash: Optional[int]
    _poly: π

    @property
    @abstractmethod
    def _ring(self) -> Ring[π, ρ]:
        ...

    def __add__(self, other: Number | τ) -> τ:
        if isinstance(other, _NUMBER_TYPES):
            other = self.__class__._term_type()(other)
        parent = self._ring | other._ring
        self_poly = parent.coerce_poly(self._poly)
        other_poly = parent.coerce_poly(other._poly)
        return self.__class__._from_raw(self_poly + other_poly)

    def __eq__(self, other: object) -> T_Eq:  # type: ignore[override]
        # MyPy requires "other: object". However, with our use a a constructor,
        # it makes no sense to compare terms with general objects. We have
        # Eq.__bool__, which supports some comparisons in Boolean contexts.
        # Same for __ne__.
        if not isinstance(other, (*_NUMBER_TYPES, self.__class__._term_type())):
            raise TypeError(f'Cannot compare Term with {type(other)}')
        lhs = self - other
        if lhs.lc() < 0:
            lhs = -lhs
        return self.__class__._eq_type()(lhs, 0)

    def __ge__(self, other: Number | τ) -> T_Ge | T_Le:
        lhs = self - other
        if lhs.lc() < 0:
            return self.__class__._le_type()(-lhs, 0)
        else:
            return self.__class__._ge_type()(lhs, 0)

    def __getstate__(self):
        return {"_poly": self._poly}

    def __gt__(self, other: Number | τ) -> T_Gt | T_Lt:
        lhs = self - other
        if lhs.lc() < 0:
            return self.__class__._lt_type()(-lhs, 0)
        else:
            return self.__class__._gt_type()(lhs, 0)

    def __hash__(self) -> int:
        if self._hash is None:
            self._hash = hash(self._poly)
        return self._hash

    @abstractmethod
    def __init__(self, number: Number) -> None:
        ...

    def __le__(self, other: Number | τ) -> T_Ge | T_Le:
        lhs = self - other
        if lhs.lc() < 0:
            return self.__class__._ge_type()(-lhs, 0)
        else:
            return self.__class__._le_type()(lhs, 0)

    def __len__(self) -> int:
        return sum(1 for _ in self.summands())

    def __lt__(self, other: Number | τ) -> T_Gt | T_Lt:
        lhs = self - other
        if lhs.lc() < 0:
            return self.__class__._gt_type()(-lhs, 0)
        else:
            return self.__class__._lt_type()(lhs, 0)

    def __ne__(self, other: object) -> T_Ne:  # type: ignore[override]
        if not isinstance(other, (*_NUMBER_TYPES, self.__class__._term_type())):
            raise TypeError(f'Cannot compare Term with {type(other)}')
        lhs = self - other
        if lhs.lc() < 0:
            lhs = -lhs
        return self.__class__._ne_type()(lhs, 0)

    def __mul__(self, other: Number | τ) -> τ:
        if isinstance(other, _NUMBER_TYPES):
            other = self.__class__._term_type()(other)
        parent = self._ring | other._ring
        self_poly = parent.coerce_poly(self._poly)
        other_poly = parent.coerce_poly(other._poly)
        return self.__class__._from_raw(self_poly * other_poly)

    def __neg__(self) -> τ:
        return self.__class__._from_raw(-self._poly)

    def __pow__(self, n: int) -> τ:
        if n < 0:
            raise ValueError(f'Negative exponent {n} not supported')
        return self.__class__._from_raw(self._poly ** n)

    def __repr__(self) -> str:
        return self._as_string(mul='*', pow='**')

    def __radd__(self, other: Number | τ) -> τ:
        assert isinstance(other, _NUMBER_TYPES)
        return self.__class__._term_type()(other) + self

    def __rmul__(self, other: Number | τ) -> τ:
        assert isinstance(other, _NUMBER_TYPES)
        return self.__class__._term_type()(other) * self

    def __rsub__(self, other: Number | τ) -> τ:
        assert isinstance(other, _NUMBER_TYPES)
        return self.__class__._term_type()(other) - self

    def __setstate__(self, state):
        self._hash = None
        self._poly = state["_poly"]

    def __str__(self) -> str:
        """Return the mathematical string representation of this term.

        >>> from logic1.theories.RCF import VV
        >>> x, y = VV.get('x', 'y')
        >>> t = (x - y + 2) ** 2
        >>> str(t)
        'x^2 - 2*x*y + y^2 + 4*x - 4*y + 4'
        """
        return self._as_string(mul='*', pow='^')

    def __sub__(self, other: Number | τ) -> τ:
        if isinstance(other, _NUMBER_TYPES):
            other = self.__class__._term_type()(other)
        parent = self._ring | other._ring
        self_poly = parent.coerce_poly(self._poly)
        other_poly = parent.coerce_poly(other._poly)
        return self.__class__._from_raw(self_poly - other_poly)

    @final
    def __xor__(self, other: object) -> Term:
        raise NotImplementedError(
            "Use ** for exponentiation, not '^', which means xor "
            "in Python, and has the wrong precedence")

    def as_constant(self) -> mpq:
        """Return this term as an :class:`mpq <.gmpy2.mpq>`.
        Raise :class:`ValueError` if this term is not constant.

        >>> from logic1.theories.RCF import VV
        >>> x = VV['x']
        >>> t = x + mpq(1, 2) - x
        >>> t
        1/2
        >>> isinstance(t, Term)
        True
        >>> isinstance(t, mpq)
        False
        >>> c = t.as_constant()
        >>> c
        mpq(1,2)
        >>> isinstance(c, mpq)
        True

        .. seealso::
            :meth:`.Term.is_constant`
        """
        if not self.is_constant():
            raise ValueError(f'{self} is not constant')
        return self.constant_coefficient()

    def as_latex(self) -> str:
        """LaTeX representation as a string. Implements the abstract method
        :meth:`.firstorder.term.Term.as_latex`.

        >>> from logic1.theories.RCF import VV
        >>> x, y = VV.get('x', 'y')
        >>> t = (x - y + 2) ** 2
        >>> t.as_latex()
        'x^{2} - 2 x y + y^{2} + 4 x - 4 y + 4'
        """
        return self._as_string(mul=' ', pow='^', exp_pre='{', exp_post='}')

    def _as_string(self, mul: str, pow: str, exp_pre: str = '', exp_post: str = '') -> str:

        def _format_first(c: mpq, d) -> str:
            m = _format_mon(d)
            if c == mpq(1):
                return m if m else f'{c}'
            elif c == mpq(-1):
                return f'-{m}' if m else f'{c}'
            elif c != mpq(0):
                return f'{c}{mul}{m}' if m else f'{c}'
            else:
                assert False, f'zero summand in {self!r}'

        def _format_next(c: mpq, d) -> str:
            m = _format_mon(d)
            if c == mpq(1):
                return f' + {m}' if m else f' + {c}'
            elif c == mpq(-1):
                return f' - {m}' if m else f' - {-c}'
            elif c > mpq(0):
                return f' + {c}{mul}{m}' if m else f' + {c}'
            elif c < mpq(0):
                return f' - {-c}{mul}{m}' if m else f' - {-c}'
            else:
                assert False, f'zero summand in {self!r}'

        def _format_var(v: Variable) -> str:
            return str(v._poly)

        def _format_mon(d: dict[Variable, int]) -> str:
            ret = ''
            for gen in self._ring.get_gens():
                v = self.__class__._variable_type()._from_gen(gen)
                e = d.get(v, 0)
                if e == 0:
                    continue
                elif e == 1:
                    ret += f'{mul}{_format_var(v)}'
                else:
                    ret += f'{mul}{_format_var(v)}{pow}{exp_pre}{e}{exp_post}'
            return ret.lstrip(mul)

        summands = list(self.summands())
        summands.reverse()
        if not summands:
            return '0'
        d, c = summands.pop()
        ret = [_format_first(c, d)]
        while summands:
            d, c = summands.pop()
            ret.append(_format_next(c, d))
        return ''.join(ret)

    def as_variable(self) -> χ:
        """Return this term as an instance of the subclass :class:`.Variable`.
        Raise :class:`ValueError` if this term is not a variable.

        >>> from logic1.theories.RCF import VV
        >>> x = VV['x']
        >>> t = x + 1 - 1
        >>> t
        x
        >>> isinstance(t, Term)
        True
        >>> isinstance(t, Variable)
        False
        >>> v = t.as_variable()
        >>> v
        x
        >>> isinstance(v, Variable)
        True

        .. seealso::
            :meth:`.Term.is_variable`
        """
        if not self.is_variable():
            raise ValueError(f'{self} is not a variable')
        return self.__class__._variable_type()._from_gen(self._poly)

    def coefficient(self, degrees: dict[χ, int]) -> τ:
        """Return the coefficient of the variables with the degrees specified in
        the ``degrees``. Mathematically, this is the coefficient in the base
        ring adjoined by the variables of this ring that are not listed in
        ``degrees``.

        >>> from logic1.theories.RCF import VV
        >>> x, y = VV.get('x', 'y')
        >>> t = (x - y + 2) ** 2
        >>> t.coefficient({x: 1, y: 1})
        -2
        >>> t.coefficient({x: 1})
        -2*y + 4
        """

        def subtract_if_subset(d1: dict[χ, int], d2: dict[χ, int]) -> Optional[dict[χ, int]]:
            """Check if d2 constraints are satisfied by d1, return remaining
            exponents. Returns d1 with keys matching d2 removed, if each key in
            d2 either has a zero exponent and does not exist in d1, or has a
            non-zero exponent and exists in d1 with the same exponent. Returns
            None otherwise.
            """
            # Verify that contraint on d2 keys is satisfied
            for name2, exp2 in d2.items():
                if name2 not in d1:
                    if exp2 != 0:
                        return None
                else:
                    var1 = name2
                    if d1[var1] != exp2:
                        return None

            # Return d1 with all variables mentioned in d2 removed
            return {var1: exp1 for var1, exp1 in d1.items() if var1 not in d2}

        # The result will have the same context as `self`. We reference
        # `degrees` only by the names of the variables.
        degrees_by_names = {var: exp for var, exp in degrees.items()}
        ret = self.__class__._term_type()(0)
        for exp_dict, coeff in self.summands():
            summand_dict = subtract_if_subset(exp_dict, degrees_by_names)
            if summand_dict is not None:
                summand = self.__class__._term_type()(coeff)
                for var, exp in summand_dict.items():
                    summand *= var ** exp
                ret += summand
        return ret

    def _coerce(self, ring: Ring[π, ρ]) -> τ:
        """Coerce the underlying polynomial of this term to the given ring.
        """
        return self.__class__._from_raw(ring.coerce_poly(self._poly))

    @abstractmethod
    def constant_coefficient(self) -> mpq:
        """Return the constant coefficient of this term.
        """
        ...

    def is_constant(self) -> bool:
        """Return :obj:`True` if this term is constant.

        >>> from logic1.theories.RCF import VV
        >>> x = VV['x']
        >>> t = x + mpq(1, 2) - x
        >>> t
        1/2
        >>> isinstance(t, mpq)
        False
        >>> t.is_constant()
        True

        .. seealso::
            - :meth:`.as_constant`
            - :external:meth:`MPolynomial_libsingular.is_constant()
              <sage.rings.polynomial.multi_polynomial_libsingular.MPolynomial_libsingular.is_constant>`
        """
        return self._poly.is_constant()

    def is_variable(self) -> bool:
        """Check if this term is a variable.

        >>> from logic1.theories.RCF import VV
        >>> x = VV['x']
        >>> t = x + 1 - 1
        >>> isinstance(t, Term)
        True
        >>> isinstance(t, Variable)
        False
        >>> t.is_variable()
        True
        """
        return self._poly in self._ring.get_gens()

